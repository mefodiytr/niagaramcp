package com.niagaramcp.json;

/**
 * Интерфейс конвертера строковых значений атрибутов xsi:type в типизированные Java-объекты.
 *
 * @param <T> целевой тип результата преобразования
 */
public interface XMLXsiTypeConverter<T> {
   /**
    * Выполняет преобразование строкового значения в объект целевого типа.
    *
    * @param var1 строковое представление значения
    * @return сконвертированное значение
    */
   T convert(String var1);
}
